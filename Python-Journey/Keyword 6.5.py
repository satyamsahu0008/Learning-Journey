# List five Python keywords and explain their purpose

#1. **if**: The `if` keyword is used to make decisions in the code. It allows you to execute a block of code only if a specified condition is true.

#2. **else**: The `else` keyword is used in conjunction with `if` to specify a block of code that will be executed if the condition in the `if` statement is false.

#3. **elif**: The `elif` keyword is short for "else if" and is used to check multiple conditions in sequence.

#4. **for**: The `for` keyword is used to create a loop that iterates over a sequence (such as a list, tuple, or string).

#5. **while**: The `while` keyword is used to create a loop that continues executing as long as a specified condition is true.